#!/bin/sh
# NeoVimore 安装脚本。纯 POSIX sh，可用 dash / ash / busybox 运行。
set -eu

ROOT=$(cd "$(dirname "$0")" && pwd)
CONFIG="$HOME/.config/nvim"
VERSION=$(sed -n 's/^.*: *\([0-9][0-9]*\.[0-9][0-9]*\).*$/\1/p' "$ROOT/init.lua" | head -n 1)

MODE=copy
NO_BACKUP=0
ASSUME_YES=0

log()  { printf '[vimore] %s\n' "$*"; }
warn() { printf '[vimore] WARN: %s\n' "$*" >&2; }
die()  { printf '[vimore] ERROR: %s\n' "$*" >&2; exit 1; }

usage() {
    cat <<EOF
Usage: $(basename "$0") [OPTIONS]

Install NeoVimore into ~/.config/nvim.

Options:
  (none)        Copy the config and write author/email to lua/vimore/user.lua
  --link        Symlink ~/.config/nvim to this repo (repo is not modified)
  --uninstall   Remove the config installed by this script
  --no-backup   Do not create .bak files when overwriting
  -y, --yes     Assume yes for prompts (author/email come from env vars)
  -V, --version Print version and exit
  -h, --help    Show this help

Environment:
  VIMORE_AUTHOR, VIMORE_EMAIL  Non-interactive author/email for file headers
EOF
}

while [ $# -gt 0 ]; do
    case "$1" in
        --link)       MODE=link; shift ;;
        --uninstall)  MODE=uninstall; shift ;;
        --no-backup)  NO_BACKUP=1; shift ;;
        -y|--yes)     ASSUME_YES=1; shift ;;
        -V|--version) echo "${VERSION:-unknown}"; exit 0 ;;
        -h|--help)    usage; exit 0 ;;
        --)           shift; break ;;
        -*)           die "unknown option: $1" ;;
        *)            die "unexpected argument: $1" ;;
    esac
done
[ $# -eq 0 ] || die "unexpected argument: $1"

backup_config() {
    [ "$NO_BACKUP" = 1 ] && return 0
    if [ -e "$CONFIG" ] || [ -L "$CONFIG" ]; then
        bak="${CONFIG}.bak.$(date +%Y%m%d-%H%M%S)"
        mv "$CONFIG" "$bak"
        log "backed up old config to $bak"
    fi
}

lua_quote() {
    printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' | tr -d '\n\r'
}

write_user() {
    dir=$1
    author=$(lua_quote "$2")
    email=$(lua_quote "$3")
    mkdir -p "$dir/lua/vimore"
    out="$dir/lua/vimore/user.lua"
    printf '%s\n' '-- Generated by setup.sh; edit freely.' > "$out"
    printf '%s\n' '-- VIMORE_AUTHOR / VIMORE_EMAIL environment variables override these.' >> "$out"
    printf '%s\n' 'return {' >> "$out"
    printf '    author = "%s",\n' "$author" >> "$out"
    printf '    email = "%s",\n' "$email" >> "$out"
    printf '%s\n' '}' >> "$out"
}

read_user_info() {
    AUTHOR="${VIMORE_AUTHOR:-}"
    EMAIL="${VIMORE_EMAIL:-}"
    if [ "$ASSUME_YES" = 0 ] && [ -t 0 ]; then
        if [ -z "$AUTHOR" ]; then
            printf 'Author name (empty to skip): '
            read -r AUTHOR || true
        fi
        if [ -z "$EMAIL" ]; then
            printf 'Email (empty to skip): '
            read -r EMAIL || true
        fi
    fi
}

verify() {
    if ! command -v nvim >/dev/null 2>&1; then
        warn "nvim not found; skipping startup check"
        return 0
    fi
    if nvim --headless -c 'qa!' </dev/null >/dev/null 2>&1; then
        log "startup check passed"
    else
        warn "Neovim reported errors at startup; run 'nvim' and check :messages"
    fi
}

case "$MODE" in
    copy)
        read_user_info
        backup_config
        mkdir -p "$HOME/.config" "$CONFIG"
        cp "$ROOT/init.lua" "$ROOT/VimMaze.vim" "$ROOT/README.md" \
           "$ROOT/README.en.md" "$CONFIG/"
        cp -R "$ROOT/lua" "$ROOT/colors" "$ROOT/tutor" "$ROOT/tests" "$CONFIG/"
        [ ! -f "$ROOT/.stylua.toml" ] || cp "$ROOT/.stylua.toml" "$CONFIG/"
        [ ! -f "$ROOT/.luarc.json" ] || cp "$ROOT/.luarc.json" "$CONFIG/"
        write_user "$CONFIG" "$AUTHOR" "$EMAIL"
        log "installed to $CONFIG"
        verify
        ;;

    link)
        if [ -L "$CONFIG" ] && [ "$(readlink "$CONFIG")" = "$ROOT" ]; then
            log "$CONFIG already points to $ROOT"
        else
            backup_config
            ln -s "$ROOT" "$CONFIG"
            log "linked $CONFIG -> $ROOT"
        fi
        log "link mode never edits $ROOT/lua/vimore/user.lua;"
        log "set VIMORE_AUTHOR / VIMORE_EMAIL or edit that file manually."
        verify
        ;;

    uninstall)
        if [ -L "$CONFIG" ] && [ "$(readlink "$CONFIG")" = "$ROOT" ]; then
            rm "$CONFIG"
        elif [ -d "$CONFIG" ] && [ -f "$CONFIG/colors/vimore.lua" ] && [ -f "$CONFIG/lua/vimore/user.lua" ]; then
            rm -rf "$CONFIG"
        else
            die "$CONFIG was not installed by this script; nothing removed"
        fi
        log "removed $CONFIG"
        ;;
esac
